import { describe, expect, it } from "vitest";
import { packageToDesiredAssets } from "@/server/packages/desired";
import { exportPackageZip } from "@/server/packages/export";
import { getLayout } from "@/server/packages/layout";
import { readPackageFolder } from "@/server/packages/read";
import { samplePackageDir, samplePolicy } from "../../../test/helpers/fixtures";
import { runRevisionBuild } from "./build";
import { applyEdits, changedPackagePaths } from "./package-files";
import { withChangelog } from "./save";

/**
 * A revision of the sample package v2, built the way a revision is built on a
 * live export: start from the assets alone (what a live space or a release can
 * supply), save the package's own non-asset files back, fix what the build
 * reports, and end with the package plus the change record. Reads
 * sample-data/packages/v2, so it never skips.
 */

const policy = samplePolicy();
const layout = getLayout(policy, "anycompany-v2");
const CHANGELOG = policy.revisions.changelog.path!;
const BAD = "memory/runbooks/retry_budget.md";
const GOOD = "memory/runbooks/retry-budget.md";
const memoryFile = (name: string) => `---\nname: ${name}\ndescription: How many times a client may retry.\n---\n\nRetry a failed call at most twice.\n`;

describe("a revision of the sample package v2", () => {
  it("rebuilds v2 from its assets and non-asset files, and the build names the one asset problem", async () => {
    const original = await readPackageFolder(samplePackageDir("v2"), { policy, layout });
    const mapped = packageToDesiredAssets(original, layout, { policy });

    // The starting package: assets only, placed and built in the layout.
    const start = exportPackageZip(mapped.assets, layout, { policy, packageName: "v3" });
    const nonAssets = [...original.files.keys()].filter((p) => !["asset", "build-artifact", "manifest"].includes(mapped.roles.get(p)?.role ?? ""));
    expect(nonAssets).toEqual(expect.arrayContaining(["README.md", "instructions/shared/handoff.md"]));
    // Only the build's own outputs and the recovered shared section source are there before the save.
    expect(nonAssets.filter((p) => start.contents.files.has(p)).sort()).toEqual(["instructions/shared/handoff.md", layout.build.validationResult!].sort());
    // The shared section source is recovered from the triage and RCA files that embed it.
    expect(start.contents.files.get("instructions/shared/handoff.md")!.equals(original.files.get("instructions/shared/handoff.md")!)).toBe(true);

    // Save 1: the package's own non-asset files, and a new memory whose name the service rejects, linked to a finding.
    const save1 = applyEdits(start.contents, [
      ...nonAssets.map((p) => ({ path: p, encoding: "base64" as const, content: original.files.get(p)!.toString("base64") })),
      { path: BAD, content: memoryFile("retry_budget") },
    ]);
    const finding = { id: "f1", auditName: "Sample benchmark", incidentId: "INCIDENT-20101", title: "Record the retry budget", citations: [{ record: 12, quote: "retry", ok: true }] };
    const changes = [{ message: "Bring back the package files and add the retry budget", changedPaths: save1.changedPaths, findingIds: ["f1"], unlinkedReason: null, createdAt: "2026-11-12T00:00:00Z" }];
    const recorded1 = withChangelog(save1.contents, policy.revisions.changelog, { name: "v3", baseLabel: "release v2", changes, findings: new Map([["f1", finding]]) });
    const build1 = runRevisionBuild(recorded1, { policy, layout, live: [] });
    // The memory name rule refuses the underscore.
    expect(build1.ok).toBe(false);
    expect(build1.results.filter((r) => r.level === "error").map((r) => [r.code, r.assetKey])).toEqual([["metadata.schema", "memory:runbooks/retry_budget"]]);

    // Save 2: rename the memory; the index is regenerated by the build.
    const save2 = applyEdits(build1.build.contents, [
      { path: BAD, content: null },
      { path: GOOD, content: memoryFile("retry-budget") },
    ]);
    expect(save2.changedPaths).toEqual([GOOD, BAD]);
    const recorded2 = withChangelog(save2.contents, policy.revisions.changelog, {
      name: "v3",
      baseLabel: "release v2",
      changes: [...changes, { message: "Rename retry_budget to retry-budget", changedPaths: save2.changedPaths, findingIds: [], unlinkedReason: "The memory name rule refuses underscores.", createdAt: "2026-11-13T00:00:00Z" }],
      findings: new Map([["f1", finding]]),
    });
    const build2 = runRevisionBuild(recorded2, { policy, layout, live: [] });
    expect(build2.results.filter((r) => r.level === "error")).toEqual([]);
    expect(build2.ok).toBe(true);
    expect(build2.build.validation.summary.status).toBe("passed");

    // The result is v2 plus the change record, the new memory and its index line, the validation summary (one more memory),
    // the manifest in the export's own format, and rebuilt skill zips.
    const final = build2.build.contents;
    const differs = changedPackagePaths(original, final).filter((p) => !(p.startsWith("skills/") && p.endsWith(".zip")));
    expect(differs.sort()).toEqual([CHANGELOG, GOOD, "memory/runbooks/INDEX.md", "reference/ASSET-METADATA.json", "reference/VALIDATION.json"].sort());
    expect(JSON.parse(final.files.get("reference/VALIDATION.json")!.toString("utf8"))).toMatchObject({ status: "passed", memories: 11 });
    const record = final.files.get(CHANGELOG)!.toString("utf8");
    expect(record).toContain("<!-- revision: v3 ");
    expect(record).toContain("| Rename retry_budget to retry-budget | `memory/runbooks/retry-budget.md`, `memory/runbooks/retry_budget.md` | None | None | None | Not linked to a finding: The memory name rule refuses underscores. |");
    expect(final.files.get("memory/runbooks/INDEX.md")!.toString("utf8")).toContain("(./retry-budget.md)");
  });
});
